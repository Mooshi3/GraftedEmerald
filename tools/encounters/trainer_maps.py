#!/usr/bin/env python3
"""Writes test/graft_trainer_maps.h: each trainer and a map it's battled on, for the all-trainers graft test.

A trainer's map is a map whose scripts name it (trainerbattle macros, multi-battle setups); rematches
(TRAINER_X_2 and up) use TRAINER_X_1's map. Trainers no Emerald map names (Frontier, link, test) are left out.
usage: tools/encounters/trainer_maps.py   (from the repo root)
"""
import glob, json, os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
opponents = open(os.path.join(ROOT, 'include/constants/opponents.h')).read()
ids = re.findall(r'#define (TRAINER_\w+)\s+\d+', opponents)
ids = [t for t in ids if t not in ('TRAINER_NONE', 'TRAINERS_COUNT') and not t.startswith('TRAINER_PARTNER')]
valid = set(ids)
skip = re.compile(r'TRAINER_(PIC|CLASS|ENCOUNTER|BACK_PIC|GENDER|BATTLE|FLAGS|TYPE|NONE|REMATCH)')

trainer_map = {}
for scripts in sorted(glob.glob(os.path.join(ROOT, 'data/maps/*/scripts.inc'))):
    folder = os.path.dirname(scripts)
    try:
        map_id = json.load(open(os.path.join(folder, 'map.json')))['id']
    except (OSError, KeyError):
        continue
    for t in re.findall(r'\b(TRAINER_\w+)\b', open(scripts).read()):
        if t in valid and not skip.match(t):
            trainer_map.setdefault(t, map_id)
for t in ids:
    m = re.match(r'(TRAINER_\w+)_(\d+)$', t)
    if t not in trainer_map and m and int(m.group(2)) >= 2 and f'{m.group(1)}_1' in trainer_map:
        trainer_map[t] = trainer_map[f'{m.group(1)}_1']

out = ['// Generated by tools/encounters/trainer_maps.py: each trainer and a map it is battled on.', '']
out += [f'    {{ {t}, {trainer_map[t]} }},' for t in ids if t in trainer_map]
open(os.path.join(ROOT, 'test/graft_trainer_maps.h'), 'w').write('\n'.join(out) + '\n')
print(f'{len(trainer_map)} of {len(ids)} trainers have a map')
